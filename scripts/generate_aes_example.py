#!/usr/bin/env python3
"""Extract FIPS 197 Appendix B data; propose kernel-checked Lean certificates.

The parser has no proof authority. Source correspondence is separately reviewable.
No cipher calculation in Python is used to decide the expected output.
"""
from pathlib import Path
import re
import json

ROOT = Path(__file__).resolve().parent.parent


def vec(values):
    return '#v[' + ', '.join(f'0x{x:02x}#8' for x in values) + ']'


def column_order(rows, block):
    return [rows[r][4*block+c] for c in range(4) for r in range(4)]


def main():
    source = (ROOT / 'source/standards/NIST.FIPS.197-upd1.txt').read_text()
    text = source[source.index('Appendix B — Cipher Example\nThe following'):]
    text = text[:text.index('Appendix C — Example Vectors')]
    plaintext = bytes.fromhex(re.search(r'Input\s+= ([0-9a-f ]+)\n', text)[1])
    key = bytes.fromhex(re.search(r'Key\s+= ([0-9a-f ]+)\n', text)[1])
    rows = {4: [], 8: [], 16: [], 20: []}
    for line in text.splitlines():
        tokens = line.split()
        if len(tokens) in rows and all(re.fullmatch('[0-9a-f]{2}', x) for x in tokens):
            rows[len(tokens)].append([int(x, 16) for x in tokens])
    assert [len(rows[n]) for n in (4, 8, 16, 20)] == [4, 4, 4, 36]
    assert list(plaintext) == column_order(rows[8], 0)
    assert list(key) == column_order(rows[8], 1)
    rounds = []
    for i in range(9):
        group = rows[20][4*i:4*i+4]
        rounds.append([column_order(group, j) for j in range(5)])
    rounds.append([column_order(rows[16], j) for j in range(3)] + [None, column_order(rows[16], 3)])
    output = column_order(rows[4], 0)
    data = dict(source='FIPS 197-upd1 Appendix B, printed pp. 34–35',
                plaintext=list(plaintext), key=list(key), output=output,
                columns=['start', 'subBytes', 'shiftRows', 'mixColumns', 'roundKey'], rounds=rounds)
    (ROOT / 'source/standards/aes-example.json').write_text(json.dumps(data, indent=2)+'\n')
    keys = [list(key)] + [r[4] for r in rounds]
    words = [v[j:j+4] for v in keys for j in range(0, 16, 4)]
    text = '''import SDitH.Spec.Rijndael
import Mathlib.Tactic

/-! FIPS 197-upd1 Appendix B, including every displayed intermediate state
and the full key expansion. Generated by scripts/generate_aes_example.py.
All arithmetic and state transitions are checked by the Lean kernel. -/

namespace SDitH.Proofs.AESExample

open Spec.Rijndael
set_option maxRecDepth 20000
set_option maxHeartbeats 8000000
set_option Elab.async false

'''
    for name, values in [('plaintext', plaintext), ('key', key), ('ciphertext', output)]:
        text += f'def {name} : State .aes128 := {vec(values)}\n\n'
    text += 'def expandedExpected : Vector Word 44 := #v[\n  ' + ',\n  '.join(map(vec, words)) + '\n]\n\n'
    text += 'def roundKeys : Vector (State .aes128) 11 := #v[\n  ' + ',\n  '.join(map(vec, keys)) + '\n]\n\n'
    for j, name in enumerate(['starts', 'afterSubBytes', 'afterShiftRows', 'afterMixColumns']):
        values = [r[j] for r in rounds if r[j] is not None]
        text += f'def {name} : Vector (State .aes128) {len(values)} := #v[\n  ' + ',\n  '.join(map(vec, values)) + '\n]\n\n'
    text += '''theorem expandedKey_checked : expandedKey .aes128 key = expandedExpected := by
  decide +kernel

theorem roundKey_checked (r : Fin 11) : roundKey .aes128 key r = roundKeys[r.val] := by
  simp only [roundKey, expandedKey_checked]
  revert r
  decide +kernel

theorem initial_checked : addRoundKey plaintext roundKeys[0] = starts[0] := by decide +kernel

theorem subBytes_checked : ∀ i : Fin 10, subBytes starts[i.val] = afterSubBytes[i.val] := by decide +kernel

theorem shiftRows_checked : ∀ i : Fin 10, shiftRows afterSubBytes[i.val] = afterShiftRows[i.val] := by decide +kernel

theorem mixColumns_checked : ∀ i : Fin 9,
    mixColumns afterShiftRows[i.val] = afterMixColumns[i.val] := by decide +kernel

theorem addRoundKey_checked : ∀ i : Fin 9,
    addRoundKey afterMixColumns[i.val] roundKeys[i.val + 1] = starts[i.val + 1] := by decide +kernel

theorem finalAdd_checked : addRoundKey afterShiftRows[9] roundKeys[10] = ciphertext := by decide +kernel

theorem round_checked (i : Fin 9) :
    Spec.Rijndael.round starts[i.val] roundKeys[i.val + 1] = starts[i.val + 1] := by
  unfold Spec.Rijndael.round
  rw [subBytes_checked ⟨i.val, by omega⟩, shiftRows_checked ⟨i.val, by omega⟩,
    mixColumns_checked i, addRoundKey_checked i]

theorem roundsThrough_checked (n : Nat) (hn : n < 10) :
    roundsThrough .aes128 key plaintext n hn = starts[n] := by
  induction n with
  | zero =>
    rw [roundsThrough, roundKey_checked]
    exact initial_checked
  | succ n ih =>
    rw [roundsThrough, ih (by omega), roundKey_checked]
    exact round_checked ⟨n, by omega⟩

theorem encrypt_checked : encrypt .aes128 key plaintext = ciphertext := by
  unfold encrypt
  rw [roundsThrough_checked, roundKey_checked]
  change finalRound starts[9] roundKeys[10] = ciphertext
  unfold finalRound
  rw [subBytes_checked ⟨9, by decide⟩, shiftRows_checked ⟨9, by decide⟩]
  exact finalAdd_checked

end SDitH.Proofs.AESExample
'''
    (ROOT / 'SDitH/Proofs/AESExample.lean').write_text(text)


if __name__ == '__main__':
    main()
