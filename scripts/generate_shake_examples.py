#!/usr/bin/env python3
"""Extract untrusted NIST trace certificates. Every generated equality is proved in Lean.

This does not compute SHAKE or certify a PDF transcription. The pinned source PDFs,
extracted text, parser, and generated input/output data remain human-reviewable.
"""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
CASES = [(k, n) for k in (128, 256) for n in (0, 5, 1605)]


def hex_prefix(text, count):
    tokens = text.split()
    assert len(tokens) >= count
    assert all(re.fullmatch(r'[0-9A-F]{2}', t) for t in tokens[:count])
    return bytes.fromhex(' '.join(tokens[:count]))


def vec(data):
    assert len(data) == 200
    lanes = [int.from_bytes(data[i:i+8], 'little') for i in range(0, 200, 8)]
    return '#v[' + ', '.join(f'0x{x:016x}' for x in lanes) + ']'


def extract(k, n):
    stem = f'SHAKE{k}_Msg{n}'
    text = (ROOT/'source/standards'/f'{stem}.txt').read_text()
    msg_text = text.split('Msg as bit string', 1)[1].split('about to call', 1)[0]
    # For the multi-block examples a separator starts the first absorption.
    msg_text = msg_text.split('About to Absorb', 1)[0]
    msg = [int(x) for x in re.findall(r'(?<!\S)[01](?!\S)', msg_text)]
    assert len(msg) == n, (stem, len(msg))
    expected = [] if n == 0 else [1, 1, 0, 0, 1] if n == 5 else [(0xA3 >> (i % 8)) & 1 for i in range(n)]
    assert msg == expected, stem
    inputs = [hex_prefix(p, 200) for p in text.split("Xor'd state (in bytes)")[1:]]
    stages = {name.lower(): [hex_prefix(p, 200) for p in text.split('After '+name)[1:]]
              for name in ('Theta', 'Rho', 'Pi', 'Chi', 'Iota')}
    rounds = stages['iota']
    output = hex_prefix(text.split('Output val is', 1)[1], 512)
    absorb_count = (n+4+2 + (1600-2*k)-1)//(1600-2*k)
    assert len(inputs) >= absorb_count
    inputs = inputs[:absorb_count]
    assert len(rounds) % 24 == 0
    return stem, msg, inputs, stages, output


def main():
    fixtures = []
    for k, n in CASES:
        stem, msg, inputs, stages, output = extract(k, n)
        rounds = stages["iota"]
        ns = f'Example{k}Msg{n}'
        lines = ['import SDitH.Proofs.SHAKEReading', 'import SDitH.Proofs.KeccakConstants', '',
                 f'/-! Untrusted trace data extracted from NIST {stem}.pdf.',
                 'Generated by scripts/generate_shake_examples.py. All transitions,',
                 'absorption and the first 64 output bytes use kernel-only',
                 'decide proofs. No native reduction is used. This is a functional regression, not a security proof. -/', '',
                 f'namespace SDitH.Proofs.SHAKE.{ns}', '',
                 'open Spec.Keccak Spec.SHAKE', '',
                 'set_option Elab.async false',
                 'set_option maxRecDepth 20000',
                 'set_option maxHeartbeats 16000000', '']
        expr = '[]' if n == 0 else '[true, true, false, false, true]' if n == 5 else \
            'List.ofFn (fun i : Fin 1605 => (0xA3 : Nat).testBit (i.val % 8))'
        lines += [f'def message : List Bool := {expr}', '']
        rate = f'rate{k}'
        for p, state in enumerate(inputs):
            trace = [state] + rounds[24*p:24*(p+1)]
            for j, value in enumerate(trace):
                lines += [f'def state{p}_{j} : State := {vec(value)}']
            for j in range(24):
                prev_stage = f'state{p}_{j}'
                for stage in ('theta', 'rho', 'pi', 'chi', 'iota'):
                    next_stage = f'state{p}_{j+1}' if stage == 'iota' else f'state{p}_{j}_{stage}'
                    if stage != 'iota':
                        lines += [f'def {next_stage} : State := {vec(stages[stage][24*p+j])}']
                    ir_arg = f' {j}' if stage == 'iota' else ''
                    lines += [f'theorem step{p}_{j}_{stage} : Spec.Keccak.{stage} {prev_stage}{ir_arg} = {next_stage} := by']
                    if stage == 'iota':
                        lines += ['  unfold Spec.Keccak.iota',
                                  f'  rw [SDitH.Proofs.Keccak.roundConstant_table (⟨{j}, by decide⟩ : Fin 24)]']
                    lines += ['  decide +kernel']
                    prev_stage = next_stage
            lines += ['', f'theorem permutation{p} : Spec.Keccak.keccak state{p}_0 = state{p}_24 := by',
                      f'  have h0 : rounds state{p}_0 0 = state{p}_0 := rfl']
            for j in range(24):
                steps = ', '.join(f'step{p}_{j}_{name}' for name in ('theta', 'rho', 'pi', 'chi', 'iota'))
                lines += [f'  have h{j+1} : rounds state{p}_0 {j+1} = state{p}_{j+1} := by',
                          f'    rw [rounds, h{j}, Spec.Keccak.round, {steps}]']
            lines += ['  exact h24', '']
            prev = 'Spec.Keccak.zero' if p == 0 else f'state{p-1}_24'
            lines += [f'theorem input{p} : inject {rate} {prev}',
                      f'    (block {rate} (padded {rate} (message ++ suffix)) {p}) = state{p}_0 := by',
                      '  apply SDitH.Proofs.Keccak.bits_injective',
                      '  funext x y z',
                      '  rw [SDitH.Proofs.SHAKE.inject_bits]',
                      '  simp only [block, padded_bit]',
                      '  simp only [message, suffix, getD_append_if,',
                      '    List.length_append, List.length_cons, List.length_nil' +
                      (', List.length_ofFn]' if n == 1605 else ']'),
                      ('  simp only [List.getD_eq_getElem?_getD, List.getElem?_ofFn]' if n == 1605 else
                       '  simp only [List.getD_eq_getElem?_getD]'),
                      '  revert x y z', '  decide +kernel', '']
        last = len(inputs)-1
        lines += [f'theorem absorption : absorb {rate} (message ++ suffix) = state{last}_24 := by',
                  f'  have hlen : (padded {rate} (message ++ suffix)).length / {rate}.value = {len(inputs)} := by decide +kernel',
                  '  dsimp only [absorb]', '  rw [hlen]', '  simp only [absorbThrough]',
                  '  rw [' + ', '.join(v for p in range(len(inputs)) for v in (f'input{p}', f'permutation{p}')) + ']', '',
                  'def expected : List Spec.DomainSeparation.Byte := [' + ', '.join(f'0x{b:02x}' for b in output[:64]) + ']', '',
                  'theorem output_matches :',
                  f'    List.ofFn (fun i : Fin 64 => byteStream {".i" if k==128 else ".v"} message i.val) = expected := by',
                  '  unfold byteStream bitStream',
                  f'  change List.ofFn (fun i : Fin 64 => (word (fun j : Fin 8 =>',
                  f'    squeezeBit {rate} (absorb {rate} (message ++ suffix)) (8 * i.val + j.val))).toFin) = expected',
                  '  rw [absorption]', '  decide', '',
                  f'end SDitH.Proofs.SHAKE.{ns}', '']
        target = ROOT/'SDitH/Proofs'/f'SHAKE{ns}.lean'
        target.write_text('\n'.join(lines))
        fixtures.append({'source': f'source/standards/{stem}.pdf',
                         'pdf_sha256':hashlib.sha256((ROOT/'source/standards'/f'{stem}.pdf').read_bytes()).hexdigest(),
                         'message_bits':msg, 'output_512_bytes_hex':output.hex(),
                         'kernel_checked_output_bytes':64, 'kernel_absorb_permutations':len(inputs),
                         'lean_file':str(target.relative_to(ROOT))})
    (ROOT/'source/standards/shake-examples.json').write_text(json.dumps(fixtures,indent=2)+'\n')
    (ROOT/'SDitH/Proofs/SHAKEExamples.lean').write_text(''.join(
        f'import SDitH.Proofs.SHAKEExample{k}Msg{n}\n' for k,n in CASES))


if __name__ == '__main__':
    main()
